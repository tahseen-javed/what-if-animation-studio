"""Writes CATALOG.md (about 1.5k tokens): every library piece by name. It is the one page Claude reads to tag a script.
python tools/catalog.py"""
from common import LIB, ROOT

L = LIB
out = ['# CATALOG', '', 'Generated by `tools/catalog.py` from `what-if-studio/src/compiler/library.json`. Do not edit by hand.', '']
counts = {k: len(L[k]) for k in ('sets', 'angles', 'cams', 'transitions', 'lights', 'poses', 'exprs', 'palettes')}
counts['props'] = sum(len(v) for v in L['props'].values())
out.append('Totals: ' + ', '.join(f'{v} {k}' for k, v in counts.items()))
out += ['', f"## Sets ({len(L['sets'])})"]
for k, s in L['sets'].items():
    var = ', '.join(f"{a}={'/'.join(map(str, v))}" for a, v in s['variants'].items()) or 'none'
    out.append(f"- `{k}` [{s['theme']}]{' no cast' if not s['cast'] else ''}{' interrupt only' if s.get('interruptOnly') else ''}: {var}")
out += ['', '## Angles', ', '.join(f'`{k}`' for k in L['angles']), '', '## Camera moves', ', '.join(f'`{k}`' for k in L['cams']),
        '', '## Transitions (entry of the incoming shot)', ', '.join(f'`{k}`' for k in L['transitions']),
        '', '## Lights', ', '.join(f'`{k}`' for k in L['lights']), '', '## Poses (expression / loop)']
out.append(', '.join(f"`{k}`" + (f" ({p.get('expr', '')}{'/' + p['loop'] if p.get('loop') else ''})" if p else '') for k, p in L['poses'].items()))
out += ['', '## Expressions', ', '.join(f'`{k}`' for k in L['exprs']), '', '## Props',
        'floor: ' + ', '.join(f'`{k}`' for k in L['props']['floor']), '', 'insert (tabletop): ' + ', '.join(f'`{k}`' for k in L['props']['insert']),
        '', '## Interrupt kinds', ', '.join(f'`{k}`' for k in L['interrupts']), '', '## Palettes (DNA grade)', ', '.join(f'`{k}`' for k in L['palettes']),
        '', '## Cast', f"hero: {', '.join(L['outfits']['hero'])}; friend: {', '.join(L['outfits']['friend'])}",
        '', '## Script tags (optional, never spoken)',
        'Put a tag on its own line or inline: `[set: kitchen]` `[light: night]` `[pose: shock]` `[interrupt: card]` `[cam: crashZoom]`.',
        'Phase 1 strips tags from the voice; the Phase 3 director applies them to the shots that cover the tagged words.', '']
(ROOT / 'CATALOG.md').write_text('\n'.join(out), encoding='utf-8')
print('CATALOG.md:', counts)
